it('CA-005-3: labels, help and options are stored as plain text without tags', function (): void {
    [, $event, $admin] = formScenario();

    $form = createForm($admin, $event, [
        formField('single_choice', [
            'label' => ['es' => '<b>Título</b><script>alert(1)</script>'],
            'help' => ['es' => '<img src=x onerror=alert(1)>Ayuda'],
            'config' => ['options' => formOptions(['<i>Sí</i>', 'No'])],
        ]),
    ]);

    $field = $form->fields[0];
    expect($field['label']['es'])->not->toContain('<')
        ->and($field['label']['es'])->toStartWith('Título')
        ->and($field['help']['es'])->toBe('Ayuda')
        ->and($field['config']['options'][0]['label']['es'])->toBe('Sí');
});

