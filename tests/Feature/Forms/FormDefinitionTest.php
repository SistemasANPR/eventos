it('CA-005-7: editing a field keeps its key and a key forged by the client is ignored', function (): void {
    [, $event, $admin] = formScenario();
    $form = createForm($admin, $event, [formField('short_text'), formField('long_text')]);
    [$first, $second] = $form->fields;

    $edited = $first;
    $edited['label']['es'] = 'Título de la propuesta';
    $forged = formField('number');
    $forged['key'] = 'f_forged';

    $updated = app(UpdateFormDefinition::class)->handle($admin, $form, ['name' => $form->name, 'fields' => [$edited, $second, $forged]]);
    $keys = array_column($updated->fields, 'key');

    expect($keys[0])->toBe($first['key'])
        ->and($keys[1])->toBe($second['key'])
        ->and($keys[2])->not->toBe('f_forged')
        ->and($keys[2])->toMatch('/^f_[a-z0-9]{6,}$/')
        ->and($updated->fields[0]['label']['es'])->toBe('Título de la propuesta');
});

it('CA-005-7: two fields that send the same key are rejected and no field is altered', function (): void {
    [, $event, $admin] = formScenario();
    $form = createForm($admin, $event, [formField('short_text'), formField('long_text')]);
    [$first, $second] = $form->fields;
    $second['key'] = $first['key'];

    expect(validationErrorKeys(fn () => app(UpdateFormDefinition::class)->handle($admin, $form, ['name' => $form->name, 'fields' => [$first, $second]])))
        ->toBe(['fields.1.key']);

    expect($form->fresh()->fields)->toEqual($form->fields);
});

