it('CA-005-1: an organizer creates a form with one field of each type and each field gets a server-generated stable key', function (): void {
    [$organization, $event, $admin] = formScenario();

    $form = createForm($admin, $event, array_map(fn (string $type): array => formField($type), allFieldTypes()));

    CurrentOrganization::set($organization);
    $stored = FormDefinition::query()->findOrFail($form->id);
    $fields = $stored->fields;
    $keys = array_column($fields, 'key');

    expect($fields)->toHaveCount(9)
        ->and(array_column($fields, 'type'))->toBe(allFieldTypes())
        ->and($keys)->each->toMatch('/^f_[a-z0-9]{6,}$/')
        ->and(array_unique($keys))->toHaveCount(9)
        ->and(array_column($fields, 'position'))->toBe([1, 2, 3, 4, 5, 6, 7, 8, 9])
        ->and($fields[0]['label'])->toEqual(['es' => 'Campo short_text', 'en' => 'Field short_text'])
        ->and($fields[0]['help'])->toEqual(['es' => 'Ayuda short_text'])
        ->and($fields[0]['required'])->toBeTrue()
        ->and($fields[0]['retiredAt'])->toBeNull()
        ->and($stored->status->value)->toBe('draft')
        ->and($stored->version)->toBe(1)
        ->and($stored->event_id)->toBe($event->id);
});

it('CA-005-1: option values are generated by the server and keep their identity when the form is edited', function (): void {
    [, $event, $admin] = formScenario();
    $form = createForm($admin, $event, [formField('single_choice')]);
    $stored = $form->fields[0];
    $values = array_column($stored['config']['options'], 'value');

    expect($values)->each->toMatch('/^o_[a-z0-9]{6,}$/')
        ->and(array_unique($values))->toHaveCount(2);

    $stored['config']['options'][0]['label']['es'] = 'Sí, claro';
    $updated = app(UpdateFormDefinition::class)->handle($admin, $form, ['name' => $form->name, 'fields' => [$stored]]);

    expect(array_column($updated->fields[0]['config']['options'], 'value'))->toBe($values);
});

