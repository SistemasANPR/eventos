it('CA-005-5: more than 40 fields, more than 50 options or more than 64 KB are rejected', function (): void {
    [, $event, $admin] = formScenario();

    $fortyOne = array_fill(0, 41, formField('short_text'));
    $manyOptions = formField('single_choice', ['config' => ['options' => formOptions(array_map(fn (int $n): string => 'Opción '.$n, range(1, 51)))]]);
    // 190 caracteres de 2 bytes: cada etiqueta es válida (máximo 200) y cada campo pesa unos 40 KB.
    $long = str_repeat('á', 190);
    $heavyField = formField('multiple_choice', ['config' => [
        'options' => formOptions(array_map(fn (int $n): string => $n.$long, range(1, 50))),
        'maxSelections' => 2,
    ]]);

    expect(validationErrorKeys(fn () => createForm($admin, $event, $fortyOne)))->toBe(['fields'])
        ->and(validationErrorKeys(fn () => createForm($admin, $event, [$manyOptions])))->toBe(['fields.0.config.options'])
        // Cada campo es válido por separado: lo que se rechaza es el peso de la definición completa.
        ->and(validationErrorKeys(fn () => createForm($admin, $event, [$heavyField])))->toBe([])
        ->and(validationErrorKeys(fn () => createForm($admin, $event, array_fill(0, 4, $heavyField))))->toBe(['fields']);

    expect(createForm($admin, $event, array_fill(0, 40, formField('short_text')))->fields)->toHaveCount(40);
});

it('CA-005-6: a member without forms.manage cannot create or edit a form', function (): void {
    [, $event, $reviewer] = formScenario(OrganizationRole::Reviewer);
    $admin = User::query()->whereHas('organizations', fn ($q) => $q->whereKey($event->organization_id))
        ->get()->first(fn (User $user): bool => $user->isNot($reviewer));
    $form = createForm($admin, $event, [formField('short_text')]);

    expect(fn () => createForm($reviewer, $event, [formField('short_text')]))->toThrow(AuthorizationException::class)
        ->and(fn () => app(UpdateFormDefinition::class)->handle($reviewer, $form, ['name' => 'Otro', 'fields' => [formField('short_text')]]))
        ->toThrow(AuthorizationException::class);
});

