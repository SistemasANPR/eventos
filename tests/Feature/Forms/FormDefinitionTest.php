it('CA-005-9: creating and changing a form is audited with who, when and the differences, without personal data', function (): void {
    [$organization, $event, $admin] = formScenario();
    $form = createForm($admin, $event, [formField('short_text')]);

    $edited = $form->fields[0];
    $edited['label']['es'] = 'Nuevo título';
    app(UpdateFormDefinition::class)->handle($admin, $form, ['name' => 'Renombrado', 'fields' => [$edited]]);

    $created = Activity::query()->where('event', 'form_definition_created')->firstOrFail();
    $changed = Activity::query()->where('event', 'form_definition_updated')->firstOrFail();

    expect($created->causer_id)->toBe($admin->id)
        ->and($created->subject_id)->toBe($form->id)
        ->and($created->properties['organization_id'])->toBe($organization->id)
        ->and($changed->causer_id)->toBe($admin->id)
        ->and($changed->created_at)->not->toBeNull()
        ->and($changed->properties['old']['name'])->toBe('Formulario de sesiones')
        ->and($changed->properties['new']['name'])->toBe('Renombrado')
        ->and($changed->properties['organization_id'])->toBe($organization->id)
        ->and(json_encode($changed->properties))->not->toContain($admin->email);
});

